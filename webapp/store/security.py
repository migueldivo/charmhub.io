"""Dependency and vulnerability snapshots for the Dependencies and Security
tabs. Snapshots are generated by scripts/generate_security_report.py."""

import json
import pathlib
from collections import Counter
from functools import lru_cache

DATA_DIR = pathlib.Path(__file__).parent / "security_data"

SEVERITIES = ["critical", "high", "medium", "low"]
SEVERITY_WEIGHTS = {"critical": 10, "high": 5, "medium": 2, "low": 0.5}

MAINTENANCE_STATUSES = [
    (
        "triaged",
        "Triaged",
        "Vulnerability assessed for impact, severity, and affected Charms.",
    ),
    (
        "in-progress",
        "In progress",
        "Developer is working on the fix, including review and testing.",
    ),
    (
        "ready-for-release",
        "Ready for release",
        "Fix approved and awaiting release.",
    ),
    ("fixed", "Fixed", "Fix released and vulnerability resolved."),
]

DEPENDENCY_TYPES = {
    "resource": "Resource",
    "application": "Workload",
    "runtime": "Runtime",
    "os-package": "OS package",
    "go-module": "Go module",
    "interface": "Interface",
    "charm-library": "Charm library",
    "python-package": "Python package",
}

DEPENDENCY_TYPES_PLURAL = {
    "resource": "Resources",
    "application": "Workloads",
    "runtime": "Runtimes",
    "os-package": "OS packages",
    "go-module": "Go modules",
    "interface": "Interfaces",
    "charm-library": "Charm libraries",
    "python-package": "Python packages",
}

# Vulnerability index bands: highest weighted exposure each letter allows.
VULNERABILITY_INDEX = [
    (10, "A"),
    (50, "B"),
    (150, "C"),
    (400, "D"),
    (800, "E"),
]


def has_security_report(charm):
    return (DATA_DIR / f"{charm}.json").is_file()


@lru_cache(maxsize=32)
def get_security_report(charm):
    path = DATA_DIR / f"{charm}.json"
    if not path.is_file():
        return None
    return json.loads(path.read_text())


def vulnerability_index(vulnerabilities):
    """Letter from A (lowest exposure) to F based on unresolved
    vulnerabilities, each weighted by severity."""
    exposure = sum(
        SEVERITY_WEIGHTS.get(vuln["severity"], SEVERITY_WEIGHTS["medium"])
        for vuln in vulnerabilities
        if vuln["status"] != "fixed"
    )
    index = next(
        (letter for limit, letter in VULNERABILITY_INDEX if exposure <= limit),
        "F",
    )
    return {"index": index, "exposure": exposure}


def summarise_report(report):
    vulns = report["vulnerabilities"]
    open_vulns = [v for v in vulns if v["status"] != "fixed"]
    severity_counts = Counter(v["severity"] for v in open_vulns)
    status_counts = Counter(v["status"] for v in vulns)
    dependency_counts = Counter(d["type"] for d in report["dependencies"])
    deps = {d["id"]: d for d in report["dependencies"]}
    affected_deps = {v["dependency"] for v in open_vulns}

    return {
        **vulnerability_index(vulns),
        "total": len(vulns),
        "open": len(open_vulns),
        "fixed": status_counts.get("fixed", 0),
        "affected_dependencies": len(affected_deps),
        "severities": [
            {"key": key, "count": severity_counts.get(key, 0)}
            for key in SEVERITIES
        ],
        "statuses": [
            {
                "key": key,
                "label": label,
                "description": description,
                "count": status_counts.get(key, 0),
            }
            for key, label, description in MAINTENANCE_STATUSES
        ],
        "dependency_types": [
            {
                "key": key,
                "label": label,
                "plural": DEPENDENCY_TYPES_PLURAL[key],
                "count": dependency_counts.get(key, 0),
                "vulnerable": len(
                    [d for d in affected_deps if deps[d]["type"] == key]
                ),
            }
            for key, label in DEPENDENCY_TYPES.items()
            if dependency_counts.get(key)
        ],
    }


@lru_cache(maxsize=1)
def _certifications():
    path = DATA_DIR / "certifications.json"
    return json.loads(path.read_text()) if path.is_file() else {}


def get_security_certification(charm):
    """Security seal of approval for a charm, with the channels it covers
    and how long each is maintained."""
    return _certifications().get(charm)
